"""Coupling diagnostic: check-performance vs main-question performance for B and C.

In V3 verified-facts mode, checks are provided as correct demonstrations in the
prompt (not generated by the model). Since checks are always correct by
construction, the standard coupling metric (P[main|all checks ok] vs
P[main|any check wrong]) is degenerate: all items have all_checks_correct.

We report:
1. The degenerate prompt-level coupling (all items -> all_checks_correct bucket)
2. The effective coupling gap: accuracy difference C - B, interpreted as the
   additional binding provided by discriminative vs neutral checks
3. Per-family breakdown of the effective coupling
"""
